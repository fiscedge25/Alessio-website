// Deterministic, smooth-looking variation: the composition is generated by
// equations, then given only a small organic perturbation rather than chaos.
const hash = n => {
  const x = Math.sin(n * 91.173 + 17.71) * 43758.5453123;
  return x - Math.floor(x);
};
const signedNoise = (n, a = 1) => (hash(n) * 2 - 1) * a;

function createPetalGeometry() {
  const shape = new THREE.Shape();
  shape.moveTo(0, 0);
  shape.bezierCurveTo(-.34, .08, -.47, .58, 0, 1.28);
  shape.bezierCurveTo(.47, .58, .34, .08, 0, 0);
  // A tiny bevel catches the light so petals no longer read as flat cards.
  const geometry = new THREE.ExtrudeGeometry(shape, { depth: .025, bevelEnabled: true, bevelThickness: .014, bevelSize: .012, bevelSegments: 2, curveSegments: 12 });
  geometry.translate(0, -.15, -.012);
  return geometry;
}

function heartPoint(t, scale = 1, depth = 0) {
  const x = 16 * Math.pow(Math.sin(t), 3);
  const y = 13 * Math.cos(t) - 5 * Math.cos(2*t) - 2 * Math.cos(3*t) - Math.cos(4*t);
  // Taller lobes and a clean lower point give the heart a more recognisable silhouette.
  const flutter = Math.sin(t * 7) * .014 + Math.cos(t * 13) * .008;
  return new THREE.Vector3(x * (.185 * scale + flutter), y * (.222 * scale + flutter) + .18, depth);
}
function addStem(end) {
  const start = new THREE.Vector3(end.x * .16, -3.35, -.25);
  const curve = new THREE.QuadraticBezierCurve3(start, new THREE.Vector3(end.x * .32, (start.y + end.y) * .52, -.4), end.clone().multiplyScalar(.95));
  const stem = new THREE.Mesh(new THREE.TubeGeometry(curve, 18, .018, 5, false), stemMat);
  flowerGroup.add(stem);
}
function makeFlower(position, size, color, delay) {
  const group = new THREE.Group(); group.position.copy(position);
  group.rotation.set(rand(-.22,.22), rand(-.22,.22), rand(-.5,.5));
  const petals = [], count = Math.round(rand(7, 9));
  const mat = new THREE.MeshStandardMaterial({ color, emissive: color, emissiveIntensity: .24, roughness: .38, metalness: .05, side: THREE.DoubleSide, transparent: true, opacity: .95 });
  const innerColor = new THREE.Color(color).lerp(new THREE.Color(0xffefd9), .30);
  const innerMat = new THREE.MeshStandardMaterial({ color: innerColor, emissive: color, emissiveIntensity: .34, roughness: .31, metalness: .08, side: THREE.DoubleSide, transparent: true, opacity: .97 });
  // Broad outer petals establish the flower; the shorter rotated inner ring adds depth.
  for (let i = 0; i < count; i++) {
    const petal = new THREE.Mesh(petalGeo, mat);
    const angle = (i / count) * Math.PI * 2 + rand(-.12,.12);
    petal.position.set(Math.cos(angle)*.055, Math.sin(angle)*.055, rand(-.04,.04));
    petal.rotation.set(rand(-.16,.16), rand(-.2,.2), angle - Math.PI/2);
    petal.userData = { angle, phase: rand(0, Math.PI*2), ring: 0, stagger: i % 2 };
    group.add(petal); petals.push(petal);
  }
  const innerCount = count - 2;
  for (let i = 0; i < innerCount; i++) {
    const petal = new THREE.Mesh(petalGeo, innerMat);
    const angle = (i / innerCount) * Math.PI * 2 + Math.PI / innerCount + rand(-.08,.08);
    petal.position.set(Math.cos(angle)*.025, Math.sin(angle)*.025, .045 + rand(-.02,.025));
    petal.rotation.set(rand(-.12,.12), rand(-.12,.12), angle - Math.PI/2);
    petal.userData = { angle, phase: rand(0, Math.PI*2), ring: 1, stagger: i % 2 };
    group.add(petal); petals.push(petal);
  }
  const inner = new THREE.Mesh(centerGeo, new THREE.MeshStandardMaterial({ color: 0xffedbe, emissive: 0xffa85a, emissiveIntensity: 1.1, roughness: .25 }));
  const core = new THREE.Mesh(new THREE.SphereGeometry(.055, 10, 8), new THREE.MeshBasicMaterial({ color: 0xfff4c7, transparent: true, opacity: .9 }));
  core.position.z = .09; group.add(inner, core); flowerGroup.add(group); addStem(position);
  flowers.push({ group, petals, inner, core, size, delay, bob: rand(0, 6.28), baseY: position.y });
}

// A parametric heart defines the outer bouquet. Its spacing is intentional,
// with a phase shift to keep the lower point from becoming mechanically even.
const edgeCount = 34;
for (let i = 0; i < edgeCount; i++) {
  const u = i / edgeCount;
  const t = u * Math.PI * 2 + .05 * Math.sin(u * Math.PI * 6);
  const radius = 1 + signedNoise(i + 3, .065);
  const p = heartPoint(t, radius, signedNoise(i + 9, .28));
  const colorIndex = Math.floor(hash(i * 4.13) * palette.length);
  makeFlower(p, .39 + hash(i * 8.7) * .19, palette[colorIndex], .9 + i * .24);
}
// The centre uses a golden-angle phyllotaxis distribution. That is the same
// botanical spacing visible in sunflower heads and gives this heart a living core.
const coreCount = 32, goldenAngle = Math.PI * (3 - Math.sqrt(5));
for (let i = 0; i < coreCount; i++) {
  const radius = Math.sqrt((i + .5) / coreCount) * .82;
  const t = i * goldenAngle + .55 * Math.sin(i * .73);
  const p = heartPoint(t, radius, signedNoise(i + 41, .33));
  p.x *= .78; p.y = p.y * .74 - .12;
  const colorIndex = Math.floor(hash(i * 2.41 + 100) * palette.length);
  makeFlower(p, .29 + hash(i * 5.31) * .2, palette[colorIndex], 2.2 + i * .18);
}

function makePoints(count, size, colorChoices, range) {
  // This is a GPU-friendly particle field: the same idea as your `phi`,
  // `theta`, `randoms`, `scales`, `colors` and `speeds` example.
  const positions = new Float32Array(count * 3);
  const basePositions = new Float32Array(count * 3);
  const colors = new Float32Array(count * 3);
  const randoms = new Float32Array(count);
  const randoms1 = new Float32Array(count);
  const scales = new Float32Array(count);
  const speeds = new Float32Array(count);
  for (let i = 0; i < count; i++) {
    const phi = Math.random() * Math.PI * 2;
    const theta = Math.acos(2 * Math.random() - 1);
    const radius = range * (.22 + Math.random() * .78);
    // Spherical distribution, stretched vertically to embrace the floral heart.
    const x = radius * Math.sin(theta) * Math.cos(phi);
    const y = radius * Math.cos(theta) * .78;
    const z = radius * Math.sin(theta) * Math.sin(phi) - 1.2;
    positions.set([x, y, z], i * 3);
    basePositions.set([x, y, z], i * 3);
    randoms[i] = Math.random();
    randoms1[i] = Math.random();
    scales[i] = Math.random() * .35;
    speeds[i] = .16 + Math.random() * .48;
    const colorIndex = Math.floor(Math.random() * colorChoices.length);
    const color = new THREE.Color(colorChoices[colorIndex]);
    colors[i * 3] = color.r;
    colors[i * 3 + 1] = color.g;
    colors[i * 3 + 2] = color.b;
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.BufferAttribute(positions,3));
  g.setAttribute('color', new THREE.BufferAttribute(colors,3));
  g.setAttribute('aRandom', new THREE.BufferAttribute(randoms,1));
  g.setAttribute('aRandom1', new THREE.BufferAttribute(randoms1,1));
  g.setAttribute('aScale', new THREE.BufferAttribute(scales,1));
  g.setAttribute('aSpeed', new THREE.BufferAttribute(speeds,1));
  const m = new THREE.ShaderMaterial({
    transparent: true, depthWrite: false, blending: THREE.AdditiveBlending,
    uniforms: { uTime: { value: 0 }, uOpacity: { value: size < .04 ? .72 : .95 }, uPointSize: { value: size < .04 ? 8.0 : 14.0 } },
    vertexShader: `
      uniform float uTime; uniform float uPointSize;
      attribute vec3 color; attribute float aRandom; attribute float aRandom1; attribute float aScale; attribute float aSpeed;
      varying vec3 vColor; varying float vAlpha;
      void main() {
        vec3 p = position;
        float phase = uTime * aSpeed + aRandom * 6.28318;
        // Every light has its own orbital curve, controlled by its arrays.
        p.x += cos(phase) * (.05 + aScale * .22);
        p.y += sin(phase * 1.37 + aRandom1 * 6.28) * (.07 + aScale * .30);
        p.z += sin(phase * .72) * (.04 + aScale * .16);
        vec4 mvPosition = modelViewMatrix * vec4(p, 1.0);
        gl_PointSize = uPointSize * (1.0 + aScale * 2.5 + sin(phase) * .24) * (24.0 / -mvPosition.z);
        gl_Position = projectionMatrix * mvPosition;
        vColor = color; vAlpha = .42 + aRandom * .58;
      }`,
    fragmentShader: `
      uniform float uOpacity; varying vec3 vColor; varying float vAlpha;
      void main() {
        float d = length(gl_PointCoord - .5);
        float glow = smoothstep(.5, .05, d);
        float core = smoothstep(.20, .0, d);
        gl_FragColor = vec4(vColor * (glow + core * .8), glow * vAlpha * uOpacity);
      }`
  });
  const points = new THREE.Points(g,m);
  points.userData = { basePositions, randoms, randoms1, scales, speeds };
  return points;
}

// A separate mathematical sculpture: particles begin as an orbiting cloud and
// are pulled onto the parametric heart before the physical flowers finish blooming.
function makeHeartConstellation(count) {
  const target = new Float32Array(count * 3), start = new Float32Array(count * 3);
  const colors = new Float32Array(count * 3), phase = new Float32Array(count), delay = new Float32Array(count), scale = new Float32Array(count);
  for (let i = 0; i < count; i++) {
    const t = Math.random() * Math.PI * 2;
    const radius = Math.sqrt(Math.random()) * 1.04;
    const p = heartPoint(t, radius, signedNoise(i + 290, .42) * (1 - radius * .45));
    target.set([p.x, p.y, p.z], i * 3);
    // A spherical start state, like the phi/theta construction discussed above.
    const phi = Math.random() * Math.PI * 2, theta = Math.acos(2 * Math.random() - 1), r = 3.8 + Math.random() * 1.8;
    start.set([r * Math.sin(theta) * Math.cos(phi), r * Math.cos(theta), r * Math.sin(theta) * Math.sin(phi) - 1.8], i * 3);
    const color = new THREE.Color(palette[Math.floor(hash(i * 3.7) * palette.length)]);
    colors.set([color.r, color.g, color.b], i * 3);
    phase[i] = Math.random() * Math.PI * 2;
    delay[i] = Math.random() * .68;
    scale[i] = .25 + Math.random() * .75;
  }
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute('position', new THREE.BufferAttribute(target, 3));
  geometry.setAttribute('aStart', new THREE.BufferAttribute(start, 3));
  geometry.setAttribute('color', new THREE.BufferAttribute(colors, 3));
  geometry.setAttribute('aPhase', new THREE.BufferAttribute(phase, 1));
  geometry.setAttribute('aDelay', new THREE.BufferAttribute(delay, 1));
  geometry.setAttribute('aScale', new THREE.BufferAttribute(scale, 1));
  const material = new THREE.ShaderMaterial({
    transparent: true, depthWrite: false, blending: THREE.AdditiveBlending,
    uniforms: { uTime: { value: 0 }, uBuild: { value: 0 } },
    vertexShader: `
      uniform float uTime; uniform float uBuild;
      attribute vec3 aStart; attribute vec3 color; attribute float aPhase; attribute float aDelay; attribute float aScale;
      varying vec3 vColor; varying float vLife;
      void main() {
        float arrive = smoothstep(aDelay, min(aDelay + .32, 1.0), uBuild);
        vec3 cloud = aStart;
        float orbit = uTime * .24 + aPhase;
        cloud.x += cos(orbit) * .18; cloud.y += sin(orbit * 1.31) * .15;
        vec3 p = mix(cloud, position, arrive);
        // After arriving, each point breathes rather than sitting still.
        p.z += sin(uTime * .7 + aPhase) * .045 * arrive;
        p.x += cos(uTime * .46 + aPhase) * .025 * arrive;
        vec4 mv = modelViewMatrix * vec4(p, 1.0);
        gl_PointSize = (2.3 + aScale * 4.8 + sin(uTime + aPhase) * .7) * (25.0 / -mv.z);
        gl_Position = projectionMatrix * mv; vColor = color; vLife = arrive;
      }`,
    fragmentShader: `
      varying vec3 vColor; varying float vLife;
      void main() {
        float d = length(gl_PointCoord - .5);
        float halo = smoothstep(.5, .02, d);
        gl_FragColor = vec4(vColor * halo * 1.35, halo * (.18 + vLife * .58));
      }`
  });
  const points = new THREE.Points(geometry, material); world.add(points);
  return points;
}
