function animate() {
  const t=clock.getElapsedTime();
  constellation.material.uniforms.uTime.value = t;
  constellation.material.uniforms.uBuild.value = THREE.MathUtils.smootherstep(t, .5, 8.7);
  constellation.rotation.z = Math.sin(t * .09) * .018;
  flowerGroup.rotation.z = Math.sin(t*.42)*.025; flowerGroup.rotation.x = Math.sin(t*.31)*.018;
  flowers.forEach(f => {
    const bloom = THREE.MathUtils.smoothstep(t, f.delay, f.delay + 3.35);
    const unfurl = THREE.MathUtils.smootherstep(t, f.delay + .4, f.delay + 4.15);
    f.group.scale.setScalar(Math.max(.001, bloom));
    f.group.position.y = f.baseY + Math.sin(t * .34 + f.bob) * .026;
    f.group.rotation.z += Math.sin(t * .12 + f.bob) * .00012;
    f.petals.forEach(p => {
      const ring = p.userData.ring;
      const growth = .22 + unfurl * .78;
      const width = f.size * (ring ? .56 : .82) * (p.userData.stagger ? .93 : 1.06);
      const length = f.size * (ring ? .65 : 1.00) * growth;
      p.scale.set(width, length, 1);
      p.rotation.x = Math.sin(t * .29 + p.userData.phase) * (.09 + ring * .05) + (1 - unfurl) * (ring ? -.42 : -.76);
    });
    f.inner.scale.setScalar(.36 + unfurl * .8);
    f.core.scale.setScalar(.45 + unfurl * .95);
  });
  // Motion is calculated in the GPU shader from the per-particle arrays.
  [dust, sparkles].forEach((field, fieldIndex) => {
    field.material.uniforms.uTime.value = t * .55;
    // Stars accumulate as the flowers arrive, rather than appearing all at once.
    field.material.uniforms.uOpacity.value = (fieldIndex ? .95 : .72) * THREE.MathUtils.smootherstep(t, 1.5, 8.8);
    field.rotation.y = t * (fieldIndex ? -.012 : .006);
  });
  trails.rotation.z=t*.012;
  detached.forEach(({p,velocity,spin})=>{p.position.add(velocity);p.rotation.z+=spin;p.rotation.y+=spin*.5;if(p.position.y<-4.5){p.position.y=4.3;p.position.x=rand(-4.5,4.5);}});
  camera.position.x += ((pointer.x*.32 + Math.sin(t*.075)*.22)-camera.position.x)*.008;
  camera.position.y += ((-.05-pointer.y*.16+Math.cos(t*.09)*.12)-camera.position.y)*.008;
  camera.lookAt(0,-.05,0); renderer.render(scene,camera); requestAnimationFrame(animate);
}
